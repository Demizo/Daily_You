import 'package:daily_you/utils/entry_share.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  const channel = MethodChannel('dev.fluttercommunity.plus/share');
  late List<MethodCall> calls;

  setUp(() {
    calls = [];
    TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger
        .setMockMethodCallHandler(channel, (call) async {
      calls.add(call);
      return 'dev.fluttercommunity.plus/share/success';
    });
  });

  tearDown(() {
    TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger
        .setMockMethodCallHandler(channel, null);
  });

  test('a log without attachments shares its text and no file list', () async {
    await shareEntry(text: 'a log', attachments: const []);

    expect(calls, hasLength(1));
    final arguments = calls.single.arguments as Map;
    expect(arguments['text'], 'a log');
    expect(arguments['paths'], isNull);
  });
}
